/**
 * Ruta de la app para un enlace de la web, o null si no es un enlace de herramienta
 * de docusmart.online por https (cualquier otro enlace no se toca).
 */
internal fun routeForWebLink(
    scheme: String?,
    host: String?,
    path: String?,
): String? {
    val isSite = scheme == "https" && host?.lowercase() in WebToolLinks.HOSTS
    val clean = path?.trimEnd('/')?.removeSuffix(".html")?.lowercase()
    return if (isSite) WebToolLinks.PATHS[clean]?.let { WebToolLinks.ROUTES[it] } else null
}
